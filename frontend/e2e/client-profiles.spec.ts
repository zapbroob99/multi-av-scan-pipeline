import { test, expect } from '@playwright/test'

test('admin edits engines and file rules for a profile; analyst is denied', async ({ page }) => {
  await page.goto('service-clients')
  await page.getByLabel('Username').fill('console-admin')
  await page.getByLabel('Password').fill('console-test-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('button', { name: 'Manage Acceptance integration' }).click()
  await page.getByRole('tab', { name: 'Scan profiles' }).click()
  await expect(page.getByRole('heading', { name: 'Acceptance routing' })).toBeVisible()
  const checkbox = page.getByRole('checkbox', { name: /Static Metadata/ })
  const review = page.getByRole('button', { name: 'Review engine changes' })
  // Nothing to review until the selection differs from what is saved, and never an empty selection.
  await expect(review).toBeDisabled()
  await checkbox.uncheck()
  await expect(review).toBeDisabled()
  await checkbox.check()
  await expect(review).toBeDisabled()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect((await checkbox.boundingBox())!.width).toBeLessThanOrEqual(20)
  await page.screenshot({ path: '../artifacts/console-e2e/client-profiles-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.getByRole('button', { name: 'Edit rules' }).click()
  // The editor replaces the card instead of repeating the profile below it.
  await expect(page.getByRole('button', { name: 'Edit rules' })).toHaveCount(0)
  const archives = page.getByRole('combobox', { name: 'Archive handling (zip, 7z, tar)', exact: true })
  await archives.selectOption('inspect')
  await expect(archives).toHaveAccessibleDescription(/MASP opens it/)
  await page.getByRole('button', { name: 'Review rules' }).click()
  await page.getByRole('button', { name: 'Save file rules' }).click()
  await expect(page.getByText('File rules saved.')).toBeVisible()
  const rules = page.getByRole('region', { name: 'File rules for Acceptance routing' })
  await expect(rules).toContainText('Archives are opened and checked')
  await page.getByRole('button', { name: 'Edit rules' }).click()
  await archives.selectOption('inherit')
  await page.getByRole('button', { name: 'Review rules' }).click()
  await page.getByRole('button', { name: 'Save file rules' }).click()
  await expect(rules).toContainText('No rules of its own')
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('button', { name: 'Sign out' }).click()
  await page.getByLabel('Username').fill('console-analyst')
  await page.getByLabel('Password').fill('console-test-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Administrator access required' })).toBeVisible()
})

test('admin creates, renames, switches and deletes named profiles inside the client dialog', async ({ page }) => {
  await page.goto('service-clients')
  await page.getByLabel('Username').fill('console-admin')
  await page.getByLabel('Password').fill('console-test-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('button', { name: 'Manage Acceptance integration' }).click()
  await page.getByRole('tab', { name: 'Scan profiles' }).click()
  const original = page.locator('article.client-profile').filter({ has: page.getByRole('heading', { name: 'Acceptance routing', exact: true }) })
  await expect(original.getByRole('button', { name: 'Delete profile' })).toBeDisabled()
  await page.getByRole('button', { name: 'Add profile' }).click()
  await page.getByLabel('Profile name').fill('Light inspection')
  await page.locator('form').getByRole('checkbox', { name: /Static Metadata/ }).check()
  await page.getByRole('button', { name: 'Review profile', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm profile change', exact: true }).click()
  const created = page.getByText('Profile created.')
  await expect(created).toBeVisible()
  await page.getByRole('tab', { name: 'Connection' }).click()
  await page.getByRole('tab', { name: 'Scan profiles' }).click()
  await expect(created).toBeVisible()
  // A successful save reloads the list, so the new profile is editable at once.
  let named = page.locator('article.client-profile').filter({ has: page.getByRole('heading', { name: 'Light inspection', exact: true }) })
  await named.getByRole('button', { name: 'Rename or disable' }).click()
  await page.getByLabel('Profile name').fill('Fast inspection')
  await page.getByRole('button', { name: 'Review profile', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Rename Light inspection to Fast inspection')
  await page.getByRole('button', { name: 'Confirm profile change', exact: true }).click()
  await expect(page.getByText('Profile saved.')).toBeVisible()
  named = page.locator('article.client-profile').filter({ has: page.getByRole('heading', { name: 'Fast inspection', exact: true }) })
  await named.getByRole('button', { name: 'Make default' }).click()
  await page.getByRole('button', { name: 'Confirm profile change', exact: true }).click()
  await expect(page.getByText('Default profile changed.')).toBeVisible()
  await expect(named.getByRole('button', { name: 'Delete profile' })).toBeDisabled()
  await expect(named.getByText(/Default profile/)).toBeVisible()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: '../artifacts/console-e2e/named-profiles-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '../artifacts/console-e2e/named-profiles-mobile.png', fullPage: true })
  await original.getByRole('button', { name: 'Make default' }).click()
  await page.getByRole('button', { name: 'Confirm profile change', exact: true }).click()
  await expect(original.getByText(/Default profile/)).toBeVisible()
  await named.getByRole('button', { name: 'Delete profile' }).click()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(named).toBeVisible()
  await named.getByRole('button', { name: 'Delete profile' }).click()
  await page.getByRole('button', { name: 'Confirm profile change', exact: true }).click()
  await expect(page.getByText('Profile deleted.')).toBeVisible()
  await expect(named).toHaveCount(0)
  await expect(original.getByText(/Default profile/)).toBeVisible()
})
