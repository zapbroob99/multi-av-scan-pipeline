import { test, expect } from '@playwright/test'

test('saved rule preview is explicit, clears after changes and works in both themes and mobile', async ({ page }) => {
  await page.goto('service-clients')
  await page.getByLabel('Username', { exact: true }).fill('console-admin')
  await page.getByLabel('Password', { exact: true }).fill('console-test-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('button', { name: 'Manage Acceptance integration' }).click()
  await expect(page.getByRole('heading', { name: '2. Profile and file rules' })).toBeVisible()
  await page.getByText('Scope and application', { exact: true }).first().click()
  await expect(page.getByText(/Accepted scans and retries keep their recorded routing snapshots/)).toBeVisible()
  let requests = 0
  page.on('request', request => { if (request.url().endsWith('/configuration/preview')) requests++ })
  await page.getByText('Try a file against saved rules').click()
  await page.getByLabel('File size', { exact: true }).fill('1.5')
  await page.getByLabel('Declared extension').fill('pdf')
  await expect(page.getByLabel('Header content type')).toHaveValue('')
  expect(requests).toBe(0)
  await page.getByRole('button', { name: 'Preview saved rules', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Matches rule 1' })).toBeVisible()
  await expect(page.getByText('Rule 1: Light check', { exact: true })).toBeVisible()
  expect(requests).toBe(1)
  await page.getByLabel('Header content type').selectOption('pe')
  await expect(page.getByRole('region', { name: 'Rule preview result' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Preview saved rules', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Matches rule 1' })).toBeVisible()
  await page.getByText('Preview scope and limitations').click()
  await expect(page.getByText(/not a scan or an allow decision/)).toBeVisible()
  await page.screenshot({ path: '../artifacts/console-e2e/rule-preview-light.png', fullPage: true })
  await page.getByRole('button', { name: 'Close dialog' }).click()
  const dark = page.getByRole('button', { name: 'Switch to dark theme' })
  if (await dark.count()) await dark.click()
  await page.getByRole('button', { name: 'Manage Acceptance integration' }).click()
  await page.getByText('Try a file against saved rules').click()
  await page.getByLabel('File size', { exact: true }).fill('100')
  await page.getByRole('button', { name: 'Preview saved rules', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Matches rule 1' })).toBeVisible()
  await page.getByRole('region', { name: 'Rule preview result' }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: '../artifacts/console-e2e/rule-preview-dark.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const dialog = page.getByRole('dialog')
  const dialogBounds = await dialog.boundingBox()
  for (const label of ['File size', 'Size unit', 'Declared extension', 'Header content type']) {
    const control = page.getByLabel(label, { exact: true })
    await control.scrollIntoViewIfNeeded()
    const bounds = await control.boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(dialogBounds!.x)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(dialogBounds!.x + dialogBounds!.width)
  }
  await page.screenshot({ path: '../artifacts/console-e2e/rule-preview-mobile.png', fullPage: true })
  await page.getByLabel('Submission path').selectOption('icap')
  await expect(page.getByRole('region', { name: 'Rule preview result' })).toHaveCount(0)
})
