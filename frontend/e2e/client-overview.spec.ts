import { test, expect } from '@playwright/test'

test('a client opens on its configuration path and returns fresh from an editor', async ({ page }) => {
  await page.goto('service-clients')
  await page.getByLabel('Username', { exact: true }).fill('console-admin')
  await page.getByLabel('Password', { exact: true }).fill('console-test-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('button', { name: 'Manage Acceptance integration' }).click()
  await expect(page.getByRole('tab', { name: 'Overview', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('heading', { name: '1. Connection' })).toBeVisible()
  await expect(page.getByRole('heading', { name: '4. Engines and worker evidence' })).toBeVisible()
  await expect(page.getByText('HTTP request body ceiling', { exact: true })).toBeVisible()
  await page.getByLabel('Submission path').selectOption('icap')
  await expect(page.getByLabel('Profile', { exact: true })).toBeDisabled()
  await expect(page.getByText(/ICAP always uses this client's default profile/)).toBeVisible()
  await page.getByLabel('Submission path').selectOption('api')
  await page.getByRole('button', { name: 'Edit profiles and rules', exact: true }).click()
  await expect(page.getByRole('tab', { name: 'Scan profiles' })).toHaveAttribute('aria-selected', 'true')
  const refreshed = page.waitForResponse(response => response.url().includes('/configuration') && response.status() === 200)
  await page.getByRole('tab', { name: 'Overview', exact: true }).click()
  await refreshed
  await expect(page.getByRole('heading', { name: '1. Connection' })).toBeVisible()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: '../artifacts/console-e2e/client-overview.png', fullPage: true })
  await page.getByRole('button', { name: 'Close dialog' }).click()
  const dark = page.getByRole('button', { name: 'Switch to dark theme' })
  if (await dark.count()) await dark.click()
  await page.getByRole('button', { name: 'Manage Acceptance integration' }).click()
  await expect(page.getByRole('heading', { name: '1. Connection' })).toBeVisible()
  await page.screenshot({ path: '../artifacts/console-e2e/client-overview-dark.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '../artifacts/console-e2e/client-overview-mobile.png', fullPage: true })
})
