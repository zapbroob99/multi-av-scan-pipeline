import { test, expect } from '@playwright/test'

test('task areas expose storage setup, scoped editors and separate notifications with role boundaries', async ({ page }) => {
  await page.goto('storage')
  await page.getByLabel('Username', { exact: true }).fill('console-admin')
  await page.getByLabel('Password', { exact: true }).fill('console-test-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  const nav = page.getByRole('navigation', { name: 'Workspace' })
  const storage = page.getByRole('navigation', { name: 'Storage sections' })
  await expect(nav.getByRole('link', { name: 'Storage', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Watch a folder', exact: true })).toBeVisible()
  await storage.getByRole('link', { name: 'Sources & access' }).click()
  await page.getByRole('link', { name: /Acceptance integration/ }).click()
  await expect(page.getByRole('heading', { name: 'Sources & access', exact: true })).toBeVisible()
  const id = page.url().split('/').pop()!
  await expect(page.locator('.scope-context')).toContainText('Acceptance integration')
  await expect(page.getByLabel('Access source')).toBeVisible()
  await page.getByRole('button', { name: 'Review storage access' }).click()
  await expect(page.getByRole('button', { name: 'Change connected system', includeHidden: true })).toBeDisabled()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.goto(`service-clients/${id}/storage`)
  await expect(page).toHaveURL(new RegExp(`/storage/access/${id}$`))
  await page.goto(`service-clients/${id}/profiles`)
  await expect(page).toHaveURL(new RegExp(`/policies/profiles/${id}$`))
  await expect(page.getByRole('heading', { name: 'Scan profiles', exact: true })).toBeVisible()
  await expect(page.locator('.scope-context')).toContainText('Acceptance integration')
  await page.goto('system/intake')
  await expect(page).toHaveURL(/\/storage\/intake$/)
  await expect(page.getByRole('heading', { name: 'File intake', exact: true })).toBeVisible()
  await nav.getByRole('link', { name: 'Integrations', exact: true }).click()
  await page.getByRole('navigation', { name: 'Integrations sections' }).getByRole('link', { name: 'ICAP gateways' }).click()
  await expect(page.getByRole('heading', { name: 'ICAP gateways', exact: true })).toBeVisible()
  await expect(page.getByRole('article', { name: 'SIEM notifications' })).toHaveCount(0)
  await nav.getByRole('link', { name: 'Administration', exact: true }).click()
  await page.getByRole('navigation', { name: 'Administration sections' }).getByRole('link', { name: 'Notifications' }).click()
  await expect(page.getByLabel('Send not-allowed files to SIEM', { exact: true })).toBeVisible()
  await expect(page.getByRole('article', { name: 'SIEM notifications' })).toBeVisible()
  await expect(page.getByLabel('Largest upload (MiB)')).toHaveCount(0)
  const before = await (await page.request.get('/api/ui/v1/scan-policy')).json()
  const siem = page.getByLabel('Send not-allowed files to SIEM', { exact: true })
  const oldValue = await siem.inputValue()
  await siem.selectOption(oldValue === '1' ? '0' : '1')
  await page.getByRole('button', { name: 'Review changes' }).click()
  await page.getByRole('button', { name: 'Save settings' }).click()
  await expect(page.getByText('Settings saved. The values below are the ones now in effect.')).toBeVisible()
  const after = await (await page.request.get('/api/ui/v1/scan-policy')).json()
  const limits = (body: { fields: { key: string; override_raw: string }[] }) => body.fields.filter(field => field.key !== 'siem_not_allowed_events').map(field => [field.key, field.override_raw])
  expect(limits(after)).toEqual(limits(before))
  await siem.selectOption(oldValue)
  await page.getByRole('button', { name: 'Review changes' }).click()
  await page.getByRole('button', { name: 'Save settings' }).click()
  await expect(page.getByText('Settings saved. The values below are the ones now in effect.')).toBeVisible()
  await page.setViewportSize({ width: 1440, height: 1000 })
  for (const theme of ['light', 'dark']) {
    const toggle = page.getByRole('button', { name: `Switch to ${theme} theme` })
    if (await toggle.count()) await toggle.click()
    await page.screenshot({ path: `../artifacts/console-e2e/task-navigation-${theme}.png`, fullPage: true })
  }
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '../artifacts/console-e2e/task-navigation-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.getByRole('button', { name: 'Sign out' }).click()
  await page.getByLabel('Username', { exact: true }).fill('console-analyst')
  await page.getByLabel('Password', { exact: true }).fill('console-test-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Administrator access required' })).toBeVisible()
  await expect(nav.getByRole('link', { name: 'Administration', exact: true })).toHaveCount(0)
  await nav.getByRole('link', { name: 'Storage', exact: true }).click()
  await expect(storage.getByRole('link', { name: 'Sources & access' })).toHaveCount(0)
  await expect(storage.getByRole('link', { name: 'File intake' })).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Watch a folder', exact: true })).toHaveCount(0)
  expect((await page.request.get(`/api/ui/v1/service-clients/${id}`)).status()).toBe(403)
})
